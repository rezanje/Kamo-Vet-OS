#!/usr/bin/env python3
"""P08 goods receipt cancellation — owner package: generate 02 and rehearse the whole package.

02-apply.sql = migration 20261028120000 verbatim + history row, one transaction (generated; never edit by hand).
01/03/04/05 are hand-written and only rehearsed here.

Rehearsal on a throwaway native cluster (scripts/native_postgres.py: unix socket only, no Docker, no DB URL,
deleted afterwards), fictional fixtures only:
  all repository migrations except P08 + simulated history → P08 suite FAILS (detects the missing change) →
  01 preflight 0 failed → 02 apply → 03 readback 0 failed → 02 again refused → P08 suite passes (rolled back) →
  04 rollback (unused) → 01 preflight 0 failed again → 02 re-apply → 03 0 failed → one fictional cancelled
  receipt committed → 04 refused, data intact → 05 freeze → authenticated can no longer execute.

Usage: python3 docs/evidence/2026-10-28-p08-penerimaan/owner-apply/build-and-verify.py BIN_DIR [--write]
  Without --write, a 02 that differs from the generated text fails the run.
"""
import hashlib
import importlib.util
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
from native_postgres import NativePostgres  # noqa: E402

VERSION, NAME = "20261028120000", "goods_receipt_cancellation"
MIGRATION = ROOT / "supabase/migrations" / f"{VERSION}_{NAME}.sql"
SUITE = ROOT / "supabase/tests/goods_receipt_cancellation.sql"


def apply_sql():
    text = MIGRATION.read_text()
    digest = hashlib.sha256(text.encode()).hexdigest()
    return ("-- P08 PEMBATALAN PENERIMAAN — APPLY, WRITES. Generated by build-and-verify.py; do not edit by hand.\n"
            f"-- One transaction: migration {MIGRATION.name} verbatim (sha256 {digest}) plus its history row.\n"
            "-- Any error, a lock wait over 5 s, or running as a role other than postgres rolls everything back.\n"
            "begin;\nset local lock_timeout = '5s';\nset local statement_timeout = '60s';\n"
            "do $$ begin\n  if current_user <> 'postgres' then\n"
            "    raise exception 'P08 apply must run as postgres (current role: %); nothing was applied', current_user;\n  end if;\n"
            f"  if exists(select 1 from supabase_migrations.schema_migrations where version = '{VERSION}') then\n"
            "    raise exception 'P08_ALREADY_APPLIED: history row exists; nothing was applied';\n  end if;\nend $$;\n"
            "-- ===== migration verbatim =====\n" + text + "\n-- ===== end migration =====\n"
            f"insert into supabase_migrations.schema_migrations(version, name) values ('{VERSION}', '{NAME}');\ncommit;\n")


def summary(db, path):
    out = db.sql((HERE / path).read_text())
    last = out.splitlines()[-1]
    assert "|0 failed|t" in last, f"{path}: {out}"
    return last


def expect_fail(db, source, fragment):
    try:
        db.sql(source)
    except RuntimeError as error:
        assert fragment in str(error), str(error)
        return
    raise AssertionError("expected failure: " + fragment)


def main():
    bin_dir, write = sys.argv[1], "--write" in sys.argv
    generated = apply_sql()
    target = HERE / "02-apply.sql"
    if write:
        target.write_text(generated)
    elif not target.exists() or target.read_text() != generated:
        raise SystemExit("02-apply.sql differs from generated text; run with --write")
    if sys.platform == "darwin":
        os.environ.setdefault("LC_ALL", "en_US.UTF-8")
    spec = importlib.util.spec_from_file_location("fx", ROOT / "scripts/test-accurate-inventory-accounting-postgres.py")
    fx = importlib.util.module_from_spec(spec); spec.loader.exec_module(fx)
    with NativePostgres(bin_dir) as db:
        # Base = every repository migration before P08, like production before the owner step.
        real_glob = Path.glob
        Path.glob = lambda self, pattern: [p for p in real_glob(self, pattern) if p.name != MIGRATION.name]
        try:
            fx.DisposablePostgres.bootstrap(db)
        finally:
            Path.glob = real_glob
        db.sql("create schema supabase_migrations; create table supabase_migrations.schema_migrations(version text primary key, name text, statements text[]);"
               "insert into supabase_migrations.schema_migrations(version) values ('20261027210000');"
               # Production posts receipts, so it has an active inventory account; the bare migration base does not.
               "insert into coa_accounts(code,name,type,normal_balance) values('1301','Fiction stock','ASET','D') on conflict(code) do update set is_active=true,is_header=false;")
        expect_fail(db, SUITE.read_text(), "ERROR")
        print("PASS P08 suite fails on the base (detects the missing change)", flush=True)
        print("PASS 01 preflight:", summary(db, "01-preflight-readonly.sql"), flush=True)
        db.sql(target.read_text())
        print("PASS 02 apply", flush=True)
        print("PASS 03 readback:", summary(db, "03-readback-readonly.sql"), flush=True)
        expect_fail(db, target.read_text(), "P08_ALREADY_APPLIED")
        print("PASS 02 again refused", flush=True)
        db.sql(SUITE.read_text())
        print("PASS P08 suite after apply (rolled back)", flush=True)
        db.sql((HERE / "04-rollback-only-if-unused.sql").read_text())
        print("PASS 04 rollback on unused install; 01 again:", summary(db, "01-preflight-readonly.sql"), flush=True)
        db.sql(target.read_text())
        print("PASS 02 re-apply; 03:", summary(db, "03-readback-readonly.sql"), flush=True)
        db.sql("""insert into branches(id,code,name,type) values('f9100000-0000-4000-8000-000000000001','P08-PKG','P08 pkg','KLINIK');
insert into purchase_orders(id,no_po,branch_id,status) values('f9500000-0000-4000-8000-000000000001','PO.P08.PKG','f9100000-0000-4000-8000-000000000001','Dipesan');
insert into goods_receipts(id,no_terima,po_id,tanggal,voided_at,void_reason) values('f9600000-0000-4000-8000-000000000001','TB.P08.PKG','f9500000-0000-4000-8000-000000000001',current_date,now(),'Fiction');""")
        before = db.sql("select count(*), max(void_reason) from goods_receipts where voided_at is not null;")
        expect_fail(db, (HERE / "04-rollback-only-if-unused.sql").read_text(), "P08_IN_USE")
        assert db.sql("select count(*), max(void_reason) from goods_receipts where voided_at is not null;") == before
        assert db.sql("select count(*) from supabase_migrations.schema_migrations where version='20261028120000';") == "1"
        print("PASS 04 refused once a receipt is cancelled; data intact", flush=True)
        db.sql((HERE / "05-freeze-if-used.sql").read_text())
        assert db.sql("select has_function_privilege('authenticated','public.cancel_goods_receipt(uuid,text,text,date)','execute');") == "f"
        print("PASS 05 freeze stops new cancellations", flush=True)


if __name__ == "__main__":
    main()
