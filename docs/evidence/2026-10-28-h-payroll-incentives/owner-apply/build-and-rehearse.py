#!/usr/bin/env python3
"""Build apply.sql from the four H migrations and rehearse preflight → apply → readback →
re-apply (idempotent) → rollback → apply again on a throwaway native PostgreSQL cluster.

No Docker, no database URL, fictional bootstrap only. Never run against production.
Usage: LC_ALL=en_US.UTF-8 python3 docs/evidence/2026-10-28-h-payroll-incentives/owner-apply/build-and-rehearse.py [pg_bin_dir]
"""
import importlib.util
from pathlib import Path
import sys

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
MIGRATIONS = [
    '20261028170000_h04_h06_commission_groups_visit_rate.sql',
    '20261028171000_h05_clinic_package_origin.sql',
    '20261028173000_h03_turnover_salary_components.sql',
    '20261028174000_h02_payslip_templates.sql',
]


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


apply_sql = ('-- H02–H06 APPLY. Generated by build-and-rehearse.py from supabase/migrations; do not edit by hand.\n'
             '-- Run preflight.sql first (SUMMARY must say 0 failed). One transaction: all or nothing. Safe to re-run.\n'
             'begin;\n' + ''.join(f'\n-- ===== {m} =====\n' + (ROOT / 'supabase/migrations' / m).read_text() for m in MIGRATIONS) + '\ncommit;\n')
(HERE / 'apply.sql').write_text(apply_sql)
print('apply.sql written from', len(MIGRATIONS), 'migrations')

native = load('native_postgres', ROOT / 'scripts/native_postgres.py')
fixture = load('fixture', ROOT / 'scripts/test-accurate-inventory-accounting-postgres.py')
BIN = sys.argv[1] if len(sys.argv) > 1 else '/opt/homebrew/opt/postgresql@16/bin'


def summary(db, file):
    out = db.sql((HERE / file).read_text())
    last = out.splitlines()[-1]
    return out, last


with native.NativePostgres(BIN) as db:
    original_glob = Path.glob
    Path.glob = lambda self, pattern: (p for p in original_glob(self, pattern) if p.name not in MIGRATIONS)
    try:
        fixture.DisposablePostgres.bootstrap(db)  # every migration except the four under rehearsal
    finally:
        Path.glob = original_glob
    out, last = summary(db, 'preflight.sql')
    assert last.startswith('SUMMARY|t|0 failed'), out
    print('preflight:', last)
    db.sql(apply_sql)
    out, last = summary(db, 'readback.sql')
    assert last == 'SUMMARY|t', out
    print('apply + readback:', last)
    db.sql(apply_sql)
    out, last = summary(db, 'preflight.sql')
    assert last.startswith('SUMMARY|t|0 failed'), out
    print('re-apply is idempotent; preflight after apply:', last)
    db.sql((HERE / 'rollback.sql').read_text())
    gone = db.sql("select to_regclass('public.payslip_templates') is null and not exists(select 1 from information_schema.columns where table_name='invoice_items' and column_name='package_item_id') and position('package_item_id' in pg_get_functiondef('public.clinic_post_invoice(uuid,text,jsonb,jsonb)'::regprocedure))=0")
    assert gone.splitlines()[-1] == 't', gone
    print('rollback: objects removed, clinic_post_invoice restored')
    db.sql(apply_sql)
    out, last = summary(db, 'readback.sql')
    assert last == 'SUMMARY|t', out
    print('apply after rollback + readback:', last)
print('REHEARSAL PASSED')
