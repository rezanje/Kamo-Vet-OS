#!/usr/bin/env python3
"""N01/P08 owner package: regenerate apply.sql from the two migrations, then rehearse on a throwaway
native PostgreSQL (scripts/native_postgres.py: unix socket only, no Docker, no DB URL, deleted afterwards),
fictional fixtures only:

  every repository migration except these two + simulated history (= production before the owner step)
  -> N01 suite FAILS on the base (detects the missing change)
  -> a function body drifted by one character is refused by preflight AND apply (exact md5)
  -> preflight -> apply -> readback -> apply again (idempotent) -> readback
  -> N01 + P08 suites + goods_receipt_cancellation suite (all roll back)
  -> rollback restores the four patched bodies byte-identical, preflight passes again
  -> apply -> readback -> one fictional link committed -> rollback refused (N01_IN_USE), data intact

Usage: python3 docs/evidence/2026-10-28-n01-p08/build-and-rehearse.py BIN_DIR [--write]
  Without --write, an apply.sql that differs from the generated text fails the run.
"""
import hashlib
import importlib.util
import os
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))
from native_postgres import NativePostgres  # noqa: E402

MIGRATIONS = [('20261029110000', 'n01_purchase_invoice_receipts'), ('20261029111000', 'p08_advance_cancel_cascade')]
FILES = [ROOT / 'supabase/migrations' / f'{v}_{n}.sql' for v, n in MIGRATIONS]
FINGERPRINT = ("select string_agg(p.oid::regprocedure::text || ':' || md5(pg_get_functiondef(p.oid)), ',' order by p.oid::regprocedure::text) "
               "from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname in "
               "('cancel_goods_receipt','guard_purchase_advance_receipt','revise_purchase_order','revise_purchase_order_prices');")


def apply_sql():
    body = ''.join(f'\n-- ===== {f.name} (sha256 {hashlib.sha256(f.read_bytes()).hexdigest()}) =====\n' + f.read_text() for f in FILES)
    history = ''.join(f"insert into supabase_migrations.schema_migrations(version, name) values ('{v}', '{n}') on conflict (version) do nothing;\n"
                      for v, n in MIGRATIONS)
    return ('-- N01/P08 APPLY — WRITES. Generated by build-and-rehearse.py from the two migrations; do not edit.\n'
            '-- One transaction; idempotent (safe to run twice). Run preflight.sql first, readback.sql after.\n'
            "begin;\nset local lock_timeout = '5s';\nset local statement_timeout = '60s';\n"
            "do $$ begin if current_user <> 'postgres' then raise exception 'N01/P08 apply must run as postgres (current role: %); nothing was applied', current_user; end if; end $$;\n"
            + body + '\n-- ===== migration history =====\n' + history + 'commit;\n')


def checks(db, file):
    out = db.sql((HERE / file).read_text()).splitlines()
    rows = [line.rsplit('|', 1) for line in out if line.count('|') == 1]
    return rows


def all_ok(db, file):
    rows = checks(db, file)
    if not rows or any(ok != 't' for _, ok in rows):
        raise AssertionError(f'{file} failed: {rows}')
    print(f'PASS {file} ({len(rows)} checks ok)', flush=True)


def expect_fail(db, source, fragment):
    try:
        db.sql(source)
    except RuntimeError as error:
        assert fragment in str(error), str(error)
        return
    raise AssertionError('expected failure: ' + fragment)


def main():
    bin_dir, write = sys.argv[1], '--write' in sys.argv
    generated = apply_sql()
    target = HERE / 'apply.sql'
    if write:
        target.write_text(generated)
    elif not target.exists() or target.read_text() != generated:
        raise SystemExit('apply.sql differs from generated text; run with --write')
    print('apply.sql sha256', hashlib.sha256(generated.encode()).hexdigest(), flush=True)
    if sys.platform == 'darwin':
        os.environ.setdefault('LC_ALL', 'en_US.UTF-8')
    spec = importlib.util.spec_from_file_location('fx', ROOT / 'scripts/test-accurate-inventory-accounting-postgres.py')
    fx = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fx)
    names = {f.name for f in FILES}
    with NativePostgres(bin_dir) as db:
        real_glob = Path.glob
        Path.glob = lambda self, pattern: [p for p in real_glob(self, pattern) if p.name not in names]
        try:
            fx.DisposablePostgres.bootstrap(db)
        finally:
            Path.glob = real_glob
        print(db.sql('select version();'), flush=True)
        db.sql("create schema supabase_migrations; create table supabase_migrations.schema_migrations(version text primary key, name text, statements text[]);"
               "insert into supabase_migrations.schema_migrations(version) values ('20261028202000');")
        expect_fail(db, (ROOT / 'supabase/tests/n01_purchase_invoice_receipts.sql').read_text(), 'ERROR')
        print('PASS N01 suite fails on the base (detects the missing change)', flush=True)
        before = db.sql(FINGERPRINT)

        tamper = ("do $t$begin execute replace(pg_get_functiondef('public.cancel_goods_receipt(uuid,text,text,date)'::regprocedure),"
                  "'Penerimaan barang tidak ditemukan','{}');end$t$;")
        db.sql(tamper.format('Penerimaan barang tidak ditemukan!'))
        if not any(ok == 'f' for _, ok in checks(db, 'preflight.sql')):
            raise AssertionError('preflight accepted a drifted function body')
        expect_fail(db, generated, 'differs from main')
        db.sql(tamper.replace("'Penerimaan barang tidak ditemukan','{}'", "'Penerimaan barang tidak ditemukan!','Penerimaan barang tidak ditemukan'"))
        assert db.sql(FINGERPRINT) == before, 'tamper not reverted'
        print('PASS drifted body refused by preflight and apply (exact md5)', flush=True)

        all_ok(db, 'preflight.sql')
        db.sql(generated)
        all_ok(db, 'readback.sql')
        db.sql(generated)
        all_ok(db, 'readback.sql')
        assert db.sql("select count(*) from supabase_migrations.schema_migrations where version in ('20261029110000','20261029111000');") == '2'
        print('PASS apply is idempotent; history rows recorded once', flush=True)
        for name in ['n01_purchase_invoice_receipts.sql', 'p08_advance_cancel_cascade.sql', 'goods_receipt_cancellation.sql']:
            db.sql((ROOT / 'supabase/tests' / name).read_text())
            print('PASS ' + name, flush=True)

        db.sql((HERE / 'rollback.sql').read_text())
        assert db.sql(FINGERPRINT) == before, 'rollback did not restore the exact pre-apply function bodies'
        assert db.sql("select to_regclass('public.purchase_invoice_receipts') is null and to_regprocedure('public.cancel_purchase_advance_cascade(uuid,text,text,text)') is null;") == 't'
        print('PASS rollback restores the 4 patched bodies byte-identical and removes new objects', flush=True)
        all_ok(db, 'preflight.sql')

        db.sql(generated)
        all_ok(db, 'readback.sql')
        db.sql("""insert into branches(id,code,name,type) values('f9100000-0000-4000-8000-000000000091','N01-PKG','N01 pkg','KLINIK');
insert into purchase_orders(id,no_po,branch_id,status) values('f9500000-0000-4000-8000-000000000091','PO.N01.PKG','f9100000-0000-4000-8000-000000000091','Diterima');
insert into goods_receipts(id,no_terima,po_id,tanggal) values('f9600000-0000-4000-8000-000000000091','TB.N01.PKG','f9500000-0000-4000-8000-000000000091',current_date);
insert into purchase_invoices(id,no_faktur,po_id,branch_id,tanggal,total) values('f9700000-0000-4000-8000-000000000091','FB.N01.PKG','f9500000-0000-4000-8000-000000000091','f9100000-0000-4000-8000-000000000091',current_date,1);
insert into purchase_invoice_receipts(invoice_id,goods_receipt_id,po_id) values('f9700000-0000-4000-8000-000000000091','f9600000-0000-4000-8000-000000000091','f9500000-0000-4000-8000-000000000091');""")
        expect_fail(db, (HERE / 'rollback.sql').read_text(), 'N01_IN_USE')
        assert db.sql('select count(*) from purchase_invoice_receipts;') == '1'
        all_ok(db, 'readback.sql')
        print('PASS rollback refused once a link exists; data and objects intact', flush=True)


if __name__ == '__main__':
    main()
