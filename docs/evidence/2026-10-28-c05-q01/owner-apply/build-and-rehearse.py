#!/usr/bin/env python3
"""Regenerate apply.sql from the two migrations, then rehearse the owner package on a throwaway
native PostgreSQL cluster (no Docker, no database URL, fictional data only):

  all earlier repository migrations -> preflight -> apply -> readback -> apply again (idempotent)
  -> rollback without flag (data archived) -> preflight -> apply -> rollback with owner flag (dropped)
  -> apply -> readback -> C05/Q01 SQL suites.

Usage: LC_ALL=en_US.UTF-8 python3 docs/evidence/2026-10-28-c05-q01/owner-apply/build-and-rehearse.py [pg bin dir]
"""
from pathlib import Path
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
MIGRATIONS = ['20261028180000_q01_new_customer_quest.sql', '20261028181000_c05_campaign_codes.sql']
BIN = Path(sys.argv[1] if len(sys.argv) > 1 else '/opt/homebrew/opt/postgresql@16/bin')

header = ('-- C05 + Q01 apply. WRITES. Generated by build-and-rehearse.py from (keep in sync):\n'
          + ''.join(f'--   supabase/migrations/{m}\n' for m in MIGRATIONS)
          + '-- Idempotent: re-running is harmless. Run preflight.sql first and readback.sql after.\nbegin;\n')
(HERE / 'apply.sql').write_text(header + '\n'.join((ROOT / 'supabase/migrations' / m).read_text() for m in MIGRATIONS) + '\ncommit;\n')

for key in [k for k in os.environ if k.startswith('PG')]:
    del os.environ[key]
os.environ.update(PSQLRC='/dev/null', TZ='Etc/UTC', LC_ALL='en_US.UTF-8')
WORK = Path(tempfile.mkdtemp(prefix='vetos-c05q01-own-', dir='/tmp'))
DATA, SOCK, PORT = WORK / 'data', WORK / 'sock', '54331'
SOCK.mkdir()


def psql(source, tuples=True):
    args = [BIN / 'psql', '-h', SOCK, '-p', PORT, '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-q']
    if tuples:
        args.append('-At')
    r = subprocess.run(args, input=source, text=True, capture_output=True)
    if r.returncode:
        raise RuntimeError(r.stderr)
    return r.stdout


def all_ok(name, out):
    rows = [line.split('|') for line in out.strip().splitlines()]
    bad = [r for r in rows if r[-1] != 't']
    if bad:
        raise RuntimeError(f'{name} not ok: {bad}')
    print(f'{name}: {len(rows)} rows ok')


FN = "select md5(pg_get_functiondef('public.apply_sale_staff_effects(uuid)'::regprocedure)) || ' ' || md5(pg_get_functiondef('public.clinic_post_invoice(uuid,text,jsonb,jsonb)'::regprocedure))"
try:
    subprocess.run([BIN / 'initdb', '-D', DATA, '-U', 'postgres', '-E', 'UTF8', '--locale=en_US.UTF-8', '--auth=trust'], check=True, capture_output=True)
    with open(DATA / 'postgresql.conf', 'a') as conf:
        conf.write(f"\nlisten_addresses = ''\nunix_socket_directories = '{SOCK}'\nport = {PORT}\ntimezone = 'Etc/UTC'\n")
    subprocess.run([BIN / 'pg_ctl', '-D', DATA, '-l', WORK / 'server.log', '-w', 'start'], check=True, capture_output=True)
    print('server:', subprocess.run([BIN / 'postgres', '--version'], capture_output=True, text=True).stdout.strip())
    psql("""create role anon; create role authenticated; create role service_role bypassrls;
create schema auth; create schema storage;
create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_user_meta_data jsonb default '{}');
create function auth.uid() returns uuid language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid$$;
create function auth.role() returns text language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claim.role',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'role')$$;
create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),'')::jsonb,'{}'::jsonb)$$;
create table storage.buckets(id text primary key,name text,public boolean);
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,owner uuid);
create publication supabase_realtime;
grant usage on schema public,auth,storage to authenticated,anon,service_role;
grant execute on all functions in schema auth to authenticated,anon,service_role;
alter default privileges in schema public grant all on tables to authenticated,service_role;
alter default privileges in schema public grant all on sequences to authenticated,service_role;""")
    earlier = [m for m in sorted((ROOT / 'supabase/migrations').glob('*.sql')) if m.name not in MIGRATIONS]
    for m in earlier:
        if m.name.startswith('0068'):
            psql("insert into coa_accounts(code,name,type,normal_balance) values('1101','Test cash','ASET','D'),('1102','Test bank','ASET','D') on conflict do nothing")
        psql('begin;\n' + m.read_text() + '\ncommit;')
    print(f'baseline: {len(earlier)} earlier migrations applied')
    base = psql(FN).strip()
    all_ok('preflight (before)', psql((HERE / 'preflight.sql').read_text()))
    psql((HERE / 'apply.sql').read_text())
    all_ok('readback', psql((HERE / 'readback.sql').read_text()))
    psql((HERE / 'apply.sql').read_text())
    all_ok('readback after re-apply (idempotent)', psql((HERE / 'readback.sql').read_text()))
    SEED = ("insert into public.vouchers (id, code, tipe, nilai) values ('{v}', 'RB{n}', 'nominal', 1000);"
            "insert into public.campaign_codes (code, voucher_id) values ('RBKODE{n}', '{v}');")
    ARCHIVED = "select count(*) from pg_class where relname = 'campaign_codes_archived_c05q01'"
    LIVE = "select count(*) from pg_class where relname in ('campaign_codes', 'quest_new_customer_claims')"
    # Rollback without the owner flag: behaviour removed, data archived (renamed), not dropped.
    psql(SEED.format(v='0b000000-0000-4000-8000-000000000001', n=1))
    psql((HERE / 'rollback.sql').read_text())
    if psql(FN).strip() != base:
        raise RuntimeError('rollback did not restore patched functions byte-for-byte')
    if psql(LIVE).strip() != '0' or psql(ARCHIVED).strip() != '1' \
            or psql("select count(*) from public.campaign_codes_archived_c05q01").strip() != '1':
        raise RuntimeError('rollback without flag must archive data-bearing tables: ' + psql(LIVE) + psql(ARCHIVED) + psql("select relname from pg_class where relname like '%archived%'"))
    print('rollback (default): functions identical to baseline; campaign code row kept in campaign_codes_archived_c05q01')
    all_ok('preflight (after rollback)', psql((HERE / 'preflight.sql').read_text()))
    psql((HERE / 'apply.sql').read_text())
    all_ok('readback (re-apply over archive)', psql((HERE / 'readback.sql').read_text()))
    # Rollback with the explicit owner flag: data-bearing objects are dropped.
    psql(SEED.format(v='0b000000-0000-4000-8000-000000000002', n=2))
    psql("select set_config('vetos.rollback_drop_data', 'yes', false);\n" + (HERE / 'rollback.sql').read_text())
    if psql(FN).strip() != base or psql(LIVE).strip() != '0' \
            or psql("select count(*) from information_schema.columns where table_schema = 'public' and (table_name, column_name) in (('sales', 'campaign_code'), ('invoices', 'campaign_code'), ('customers', 'imported_at'))").strip() != '0':
        raise RuntimeError('rollback with flag must drop data-bearing objects')
    print('rollback (owner flag): functions identical to baseline; new tables/columns dropped')
    psql((HERE / 'apply.sql').read_text())
    all_ok('readback (re-apply)', psql((HERE / 'readback.sql').read_text()))
    for suite in ['c05_campaign_codes.sql', 'q01_new_customer_quest.sql']:
        print(psql((ROOT / 'supabase/tests' / suite).read_text()).strip().splitlines()[-1])
    print('apply.sql sha256', hashlib.sha256((HERE / 'apply.sql').read_bytes()).hexdigest())
finally:
    if (DATA / 'postmaster.pid').exists():
        subprocess.run([BIN / 'pg_ctl', '-D', DATA, '-m', 'immediate', 'stop'], capture_output=True)
    shutil.rmtree(WORK, ignore_errors=True)
    print('cleanup: temp cluster removed' if not WORK.exists() else f'cleanup FAILED: {WORK}')
