#!/usr/bin/env python3
"""M05 optional invoice/due date — owner package: generate 02/04 and rehearse the whole package.

02-apply.sql = migration 20261027210000 verbatim + history row, one transaction (generated; never edit by hand).
04-rollback-only-if-unused.sql = restores NOT NULL, drops the two CHECKs and puts back the M05 review function
  verbatim from 20261027180000 (generated, so the restored body cannot drift); refuses once any opening invoice
  without a date exists.
01/03 are hand-written and only rehearsed here.

Rehearsal on a throwaway native cluster (scripts/native_postgres.py: unix socket only, no Docker, no DB URL,
deleted afterwards), fictional fixtures only:
  all repository migrations + simulated history → 04 rollback on an install without undated invoices (back to
  the M05 base) → new SQL suite FAILS on that base (it detects the missing change) → M05 suite passes → M05
  fixture committed as "old transactions" and fingerprinted → 01 preflight 0 failed → 02 apply → 03 readback
  0 failed → old transactions byte-identical → 02 again refused → new SQL suite passes (rolled back) → one undated
  fictional batch committed → 04 rollback refused, data intact → 03 still 0 failed.

Usage: python3 docs/evidence/2026-10-27-m05-optional-dates/owner-apply/build-and-verify.py BIN_DIR [--write]
  Without --write, a 02/04 that differs from the generated text fails the run.
"""
import hashlib
import importlib.util
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
from native_postgres import NativePostgres  # noqa: E402

VERSION, NAME = "20261027210000", "opening_invoice_optional_dates"
MIGRATION = ROOT / "supabase/migrations" / f"{VERSION}_{NAME}.sql"
BASE = ROOT / "supabase/migrations/20261027180000_opening_ap_ar_invoices.sql"
M05_SUITE = ROOT / "supabase/tests/opening_ap_ar_invoices.sql"
SUITE = ROOT / "supabase/tests/opening_invoice_optional_dates.sql"
OLD_MD5, NEW_MD5 = "7902334a2c9f7dcc8b3c4c0bcba6bc1e", "21e8cca732648c114ea9e5b64a75d79b"
GUARD = ("do $$ begin\n  if current_user <> 'postgres' then\n"
         "    raise exception 'M05D {what} must run as postgres (current role: %); nothing was {done}', current_user;\n  end if;\n")
# Old rows that must not change: every table the apply touches or that records an opening batch.
SNAPSHOT = ";\n".join(
    f"select '{t}', count(*), md5(coalesce(string_agg(row_to_json(x)::text, '|' order by x.id::text), '')) from public.{t} x"
    for t in ["purchase_invoices", "sales_invoices", "opening_invoice_batches", "opening_invoice_lines",
              "purchase_invoice_payments", "sales_receipts", "journal_entries", "journal_lines"]) + ";"


def old_review_function():
    src = BASE.read_text()
    start = src.index("create function public.opening_invoice_review(p_payload jsonb)")
    end = src.index("revoke all on function public.opening_invoice_review(jsonb) from public,anon,authenticated,service_role;")
    return src[start:end].replace("create function", "create or replace function", 1)


def apply_sql():
    text = MIGRATION.read_text()
    digest = hashlib.sha256(text.encode()).hexdigest()
    return ("-- M05 TANGGAL OPSIONAL — APPLY, WRITES. Generated by build-and-verify.py; do not edit by hand.\n"
            f"-- One transaction: migration {MIGRATION.name} verbatim (sha256 {digest}) plus its history row.\n"
            "-- Any error, a lock wait over 5 s, or running as a role other than postgres rolls everything back.\n"
            "begin;\nset local lock_timeout = '5s';\nset local statement_timeout = '60s';\n"
            + GUARD.format(what="apply", done="applied")
            + "  if (select count(*) from supabase_migrations.schema_migrations where version = '20261027180000') <> 1 then\n"
            "    raise exception 'M05D_PREREQUISITE_MISSING: M05 20261027180000 not recorded; nothing was applied';\n  end if;\n"
            f"  if exists(select 1 from supabase_migrations.schema_migrations where version = '{VERSION}') then\n"
            "    raise exception 'M05D_ALREADY_APPLIED: history row exists; nothing was applied';\n  end if;\nend $$;\n\n"
            + text.rstrip("\n") + "\n\n"
            f"insert into supabase_migrations.schema_migrations(version, name) values ('{VERSION}', '{NAME}');\ncommit;\n")


def rollback_sql():
    return ("-- M05 TANGGAL OPSIONAL — ROLLBACK, WRITES. Generated by build-and-verify.py; do not edit by hand.\n"
            "-- Only on a release decision, and only while NO opening invoice without a date exists. Refuses\n"
            "-- (M05D_ROLLBACK_REFUSED) otherwise: an undated opening invoice is a financial record and no date is\n"
            "-- ever invented to make a rollback fit. Restores the M05 review function verbatim from\n"
            f"-- {BASE.name}. One transaction; any error = no change.\n"
            "begin;\nset local lock_timeout = '5s';\nset local statement_timeout = '60s';\n"
            + GUARD.format(what="rollback", done="changed")
            + f"  if (select count(*) from supabase_migrations.schema_migrations where version = '{VERSION}') <> 1 then\n"
            f"    raise exception 'M05D_ROLLBACK_NOT_APPLIED: history row {VERSION} missing; nothing was changed';\n  end if;\nend $$;\n"
            "lock table public.opening_invoice_batches, public.opening_invoice_lines, public.purchase_invoices, public.sales_invoices in share row exclusive mode;\n"
            "do $$ begin\n"
            "  if exists(select 1 from public.purchase_invoices where tanggal is null or jatuh_tempo is null)\n"
            "   or exists(select 1 from public.sales_invoices where tanggal is null or jatuh_tempo is null)\n"
            "   or exists(select 1 from public.opening_invoice_lines where tanggal is null or jatuh_tempo is null) then\n"
            "    raise exception 'M05D_ROLLBACK_REFUSED: opening invoices without a date already exist; nothing was changed';\n  end if;\nend $$;\n\n"
            + old_review_function()
            + "revoke all on function public.opening_invoice_review(jsonb) from public,anon,authenticated,service_role;\n"
            "alter table public.purchase_invoices drop constraint purchase_invoices_tanggal_wajib_check;\n"
            "alter table public.sales_invoices drop constraint sales_invoices_tanggal_wajib_check;\n"
            "alter table public.purchase_invoices alter column tanggal set not null, alter column jatuh_tempo set not null;\n"
            "alter table public.sales_invoices alter column tanggal set not null, alter column jatuh_tempo set not null;\n"
            "alter table public.opening_invoice_lines alter column tanggal set not null, alter column jatuh_tempo set not null;\n"
            f"delete from supabase_migrations.schema_migrations where version = '{VERSION}';\ncommit;\n")


def summary_ok(output, label):
    last = output.strip().splitlines()[-1]
    assert last.startswith("SUMMARY|0 failed|0 failed|t"), f"{label} did not pass:\n{output}"


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    generated = {"02-apply.sql": apply_sql(), "04-rollback-only-if-unused.sql": rollback_sql()}
    for name, text in generated.items():
        target = HERE / name
        if "--write" in sys.argv:
            target.write_text(text)
        elif not target.exists() or target.read_text() != text:
            sys.exit(f"{name} differs from the generated text; rerun with --write and review the diff")
    if sys.platform == "darwin":
        os.environ.setdefault("LC_ALL", "en_US.UTF-8")
    spec = importlib.util.spec_from_file_location("fixture", ROOT / "scripts/test-accurate-inventory-accounting-postgres.py")
    fixture = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fixture)
    log = []
    say = lambda line: (print(line, flush=True), log.append(line))
    files = {name: (HERE / name).read_text() for name in ["01-preflight-readonly.sql", "02-apply.sql", "03-readback-readonly.sql", "04-rollback-only-if-unused.sql"]}
    for name, text in files.items():
        say(f"sha256 {hashlib.sha256(text.encode()).hexdigest()}  {name}")
    say(f"sha256 {hashlib.sha256(MIGRATION.read_bytes()).hexdigest()}  {MIGRATION.relative_to(ROOT)}")
    fingerprint = "select md5(prosrc) from pg_proc where oid = 'public.opening_invoice_review(jsonb)'::regprocedure"
    not_null = ("select count(*) from information_schema.columns where table_schema = 'public' and table_name in "
                "('purchase_invoices','sales_invoices','opening_invoice_lines') and column_name in ('tanggal','jatuh_tempo') and is_nullable = 'NO'")
    with NativePostgres(sys.argv[1]) as db:
        fixture.DisposablePostgres.bootstrap(db)
        server = db.sql("show server_version")
        say(f"Bootstrapped {len(list((ROOT / 'supabase/migrations').glob('*.sql')))} repository migrations on PostgreSQL {server}")
        versions = sorted(p.name.split("_", 1) for p in (ROOT / "supabase/migrations").glob("*.sql"))
        db.sql("create schema supabase_migrations; create table supabase_migrations.schema_migrations(version text primary key, statements text[], name text);\n"
               + "".join(f"insert into supabase_migrations.schema_migrations(version,name) values('{v}','{n[:-4]}') on conflict do nothing;\n" for v, n in versions))
        db.sql("insert into coa_accounts(code,name,type,normal_balance) values('2101','Fiction AP','LIABILITAS','K'),('1201','Fiction AR','ASET','D'),('3101','Fiction equity','EKUITAS','K') on conflict do nothing;")
        say("Simulated migration history (all versions recorded) and fictional COA 2101/1201/3101")
        assert db.sql(fingerprint) == NEW_MD5, "repository migration does not produce the expected review function"
        db.sql(files["04-rollback-only-if-unused.sql"])
        assert db.sql(fingerprint) == OLD_MD5 and db.sql(not_null) == "6"
        assert db.sql("select count(*) from pg_constraint where conname like '%_tanggal_wajib_check'") == "0"
        assert db.sql(f"select count(*) from supabase_migrations.schema_migrations where version = '{VERSION}'") == "0"
        say("PASS 04 rollback without undated invoices: back to the M05 base (6 columns NOT NULL, review function md5 = M05)")
        try:
            db.sql(SUITE.read_text())
            raise AssertionError("optional-date suite passed on the M05 base")
        except RuntimeError as error:
            assert "Undated rows not accepted" in str(error), error
        say("PASS optional-date SQL suite FAILS on the M05 base (undated rows rejected) — the suite detects the change")
        db.sql(M05_SUITE.read_text())
        say("PASS M05 SQL suite on the M05 base (rolled back)")
        db.sql(M05_SUITE.read_text().rsplit("rollback;", 1)[0] + "commit;\n")
        before = db.sql(SNAPSHOT)
        say("Committed the M05 fixture as old transactions (dated batch, payment, receipt, journals); fingerprinted 8 tables")
        summary_ok(db.sql(files["01-preflight-readonly.sql"]), "preflight")
        say("PASS 01 preflight: 0 failed")
        db.sql(files["02-apply.sql"])
        say("PASS 02 apply")
        summary_ok(db.sql(files["03-readback-readonly.sql"]), "readback")
        say("PASS 03 readback: 0 failed")
        assert db.sql(SNAPSHOT) == before, "apply changed existing rows"
        say("PASS old transactions byte-identical after apply (row count and md5 of every row, 8 tables)")
        try:
            db.sql(files["02-apply.sql"])
            raise AssertionError("second apply was accepted")
        except RuntimeError as error:
            assert "M05D_ALREADY_APPLIED" in str(error), error
        summary_ok(db.sql(files["03-readback-readonly.sql"]), "readback after refused re-apply")
        say("PASS second 02 apply refused (M05D_ALREADY_APPLIED); readback unchanged")
        db.sql(SUITE.read_text())
        say("PASS optional-date SQL suite after apply (rolled back), next to the committed M05 batch")
        db.sql(SUITE.read_text().rsplit("rollback;", 1)[0] + "commit;\n")
        undated = "select count(*) from purchase_invoices where opening_batch_id is not null and (tanggal is null or jatuh_tempo is null); select count(*) from sales_invoices where opening_batch_id is not null and tanggal is null"
        assert db.sql(undated).splitlines() == ["3", "1"], db.sql(undated)
        say("Committed one fictional batch with undated invoices (3 payables, 1 receivable without a date)")
        try:
            db.sql(files["04-rollback-only-if-unused.sql"])
            raise AssertionError("rollback accepted with undated invoices")
        except RuntimeError as error:
            assert "M05D_ROLLBACK_REFUSED" in str(error), error
        assert db.sql(undated).splitlines() == ["3", "1"] and db.sql(fingerprint) == NEW_MD5
        summary_ok(db.sql(files["03-readback-readonly.sql"]), "readback after refused rollback")
        say("PASS 04 rollback refused once undated invoices exist (M05D_ROLLBACK_REFUSED); data and readback intact")
    (HERE / f"rehearsal-pg{server.split()[0]}.log").write_text("\n".join(log) + "\n")


if __name__ == "__main__":
    main()
