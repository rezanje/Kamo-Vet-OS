#!/usr/bin/env python3
"""K02 owner package: (re)generate the read-only preflight/readback SQL and the rollback SQL from the
migration's own patch list, derive the expected fingerprints from a throwaway native PostgreSQL cluster,
then rehearse: preflight -> apply -> readback -> rollback -> preflight -> re-apply -> readback + K02 suite.

Never accepts a database URL. The cluster lives in a fresh temp dir, unix socket only, and is deleted.
Usage (repo root, Homebrew postgresql@16/@17, no Docker):
  python3 docs/evidence/2026-10-26-k02-bmhp/owner-apply/build-and-verify.py [/opt/homebrew/opt/postgresql@17/bin]
"""
from pathlib import Path
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
MIG = ROOT / 'supabase/migrations/20261026100000_k02_procedure_bmhp.sql'
BIN = Path(sys.argv[1] if len(sys.argv) > 1 else '/opt/homebrew/opt/postgresql@17/bin')

source = MIG.read_text()
VALUES = re.search(r"for p in select \* from \(values\n(.*?)\n \) as patches\(sig, old_text, new_text\) loop", source, re.S).group(1)
PATCHED = list(dict.fromkeys(re.findall(r"\('(public\.[a-z_]+\([a-z,]*\))',", VALUES)))
NEW = ['public.clinic_bmhp_supported()', 'public.guard_prescription_bmhp()', 'public.guard_invoice_item_bmhp()',
       'clinic_private.bmhp_issue(uuid,uuid,text,date)', 'clinic_private.bmhp_edit_plan(uuid,jsonb,uuid,text)']
assert len(PATCHED) == 6 and VALUES.count("\n  ('public.") == 18, (PATCHED, VALUES.count("\n  ('public."))

WORK = Path(tempfile.mkdtemp(prefix='vetos-k02-owner-'))
DATA, SOCK, PORT = WORK / 'data', WORK / 'sock', '54331'
ENV = {k: v for k, v in os.environ.items() if not k.startswith('PG')}
ENV.update(PSQLRC='/dev/null', TZ='Etc/UTC', LC_ALL='en_US.UTF-8')
LOG = []


def psql(sql, check=True):
    r = subprocess.run([BIN / 'psql', '-X', '-h', SOCK, '-p', PORT, '-U', 'postgres', '-d', 'postgres',
                        '-v', 'ON_ERROR_STOP=1', '-At', '-F', '|'], input=sql, text=True, capture_output=True, env=ENV)
    if check and r.returncode:
        raise RuntimeError(r.stderr)
    return r


def rows(sql):
    return [line.split('|') for line in psql(sql).stdout.splitlines() if line]


def fingerprint(sigs):
    return {s: rows(f"select md5(prosrc), prosecdef from pg_proc where oid = to_regprocedure('{s}')")[0] for s in sigs}


def sql_values(pairs):
    return ',\n    '.join(f"('{a}', '{b}')" for a, b in pairs)


CHECKS_TAIL = """
)
select check_name, expected, actual,
  case when expected is null then null else actual is not distinct from expected end as ok
from checks
union all
select 'SUMMARY', '0 failed',
  count(*) filter (where expected is not null and actual is distinct from expected) || ' failed',
  count(*) filter (where expected is not null and actual is distinct from expected) = 0
from checks;
"""


def render(pre, post):
    fp_pre = sql_values((s, pre[s][0]) for s in PATCHED)
    fp_post = sql_values((s, post[s][0]) for s in PATCHED + NEW)
    secdef = sql_values((s, 'true' if post[s][1] == 't' else 'false') for s in PATCHED + NEW)
    secdef_pre = sql_values((s, 'true' if pre[s][1] == 't' else 'false') for s in PATCHED)
    sigs = ',\n    '.join(f"('{s}')" for s in PATCHED)
    preflight = f"""-- K02 PREFLIGHT — READ ONLY. Generated by build-and-verify.py; do not edit by hand.
-- Run each query on its own (select the query text, then Run). Nothing here writes.

-- QUERY A — readiness. Every row with an expected value must show ok = true; last row SUMMARY must say "0 failed".
with patches(sig, old_text, new_text) as (values
{VALUES}
), anchors as (
  select row_number() over () as n, sig, old_text, pg_get_functiondef(to_regprocedure(sig)) as def from patches
), checks(check_name, expected, actual) as (
  select 'info: server version', null, current_setting('server_version')
  union all select 'info: database', null, current_database()
  union all select 'prerequisite: 20261026090000 inpatient_rx_evidence present', 'true', (to_regclass('public.inpatient_rx_evidence') is not null)::text
  union all select 'not yet applied: clinic_bmhp_supported() absent', 'true', (to_regprocedure('public.clinic_bmhp_supported()') is null)::text
  union all select 'not yet applied: bmhp_components columns', '0', (select count(*) from information_schema.columns where table_schema = 'public' and column_name = 'bmhp_components')::text
  union all select 'not yet applied: K02 triggers', '0', (select count(*) from pg_trigger where tgname in ('k02_prescription_bmhp', 'k02_invoice_item_bmhp'))::text
  union all select 'dependency: schema clinic_private', 'true', (to_regnamespace('clinic_private') is not null)::text
  union all select 'dependency: public.' || f, 'true', exists(select 1 from pg_proc where proname = f and pronamespace = 'public'::regnamespace)::text
    from unnest(array['stock_out_fifo', 'stock_in_fifo', 'inventory_is_average']) f
  union all select 'fingerprint (same as repository): ' || f.sig, f.md5, (select md5(prosrc) from pg_proc where oid = to_regprocedure(f.sig))
    from (values
    {fp_pre}
    ) f(sig, md5)
  union all select 'security definer: ' || f.sig, f.v, (select prosecdef::text from pg_proc where oid = to_regprocedure(f.sig))
    from (values
    {secdef_pre}
    ) f(sig, v)
  union all select 'anchor ' || lpad(n::text, 2, '0') || ' found exactly once: ' || sig, '1',
    ((length(def) - length(replace(def, old_text, ''))) / length(old_text))::text from anchors{CHECKS_TAIL}
-- QUERY B — migration history (needs the Supabase CLI history table). Expect newest row 20261026090000
-- (inpatient_rx_evidence) and NO row 20261026100000. If the table does not exist, note it and tell the developer.
select version, name from supabase_migrations.schema_migrations order by version desc limit 5;

-- QUERY C — keep a copy of the six function definitions K02 will patch (export the result as CSV and store
-- it with the backup note). Only needed for the fallback rollback path.
select s.sig, pg_get_functiondef(to_regprocedure(s.sig)) as definition_before_k02
from (values
    {sigs}
) s(sig);
"""
    readback = f"""-- K02 READBACK — READ ONLY. Generated by build-and-verify.py; do not edit by hand.
-- Run right after the apply step, each query on its own.

-- QUERY A — the migration is fully in place. Every row with an expected value must show ok = true;
-- last row SUMMARY must say "0 failed". The two "info: rows with BMHP" lines should be 0 right after apply.
with patches(sig, old_text, new_text) as (values
{VALUES}
), anchors as (
  select row_number() over () as n, sig, new_text, pg_get_functiondef(to_regprocedure(sig)) as def from patches
), checks(check_name, expected, actual) as (
  select 'info: server version', null, current_setting('server_version')
  union all select 'info: database', null, current_database()
  union all select 'applied: clinic_bmhp_supported() present', 'true', (to_regprocedure('public.clinic_bmhp_supported()') is not null)::text
  union all select 'applied: bmhp_components columns', '2', (select count(*) from information_schema.columns where table_schema = 'public' and column_name = 'bmhp_components')::text
  union all select 'applied: K02 triggers enabled', '2', (select count(*) from pg_trigger where tgname in ('k02_prescription_bmhp', 'k02_invoice_item_bmhp') and tgenabled = 'O')::text
  union all select 'fingerprint (same as tested): ' || f.sig, f.md5, (select md5(prosrc) from pg_proc where oid = to_regprocedure(f.sig))
    from (values
    {fp_post}
    ) f(sig, md5)
  union all select 'security definer: ' || f.sig, f.v, (select prosecdef::text from pg_proc where oid = to_regprocedure(f.sig))
    from (values
    {secdef}
    ) f(sig, v)
  union all select 'grant: authenticated may call clinic_bmhp_supported()', 'true', has_function_privilege('authenticated', 'public.clinic_bmhp_supported()', 'EXECUTE')::text
  union all select 'grant: anon may call clinic_bmhp_supported()', 'false', has_function_privilege('anon', 'public.clinic_bmhp_supported()', 'EXECUTE')::text
  union all select 'grant: authenticated may call ' || f, 'false', has_function_privilege('authenticated', f, 'EXECUTE')::text
    from unnest(array['public.guard_prescription_bmhp()', 'public.guard_invoice_item_bmhp()',
      'clinic_private.bmhp_issue(uuid,uuid,text,date)', 'clinic_private.bmhp_edit_plan(uuid,jsonb,uuid,text)']) f
  union all select 'patch ' || lpad(n::text, 2, '0') || ' present exactly once: ' || sig, '1',
    ((length(def) - length(replace(def, new_text, ''))) / length(new_text))::text from anchors
  union all select 'info: rows with BMHP in prescription_items', null, (select count(*) from public.prescription_items where bmhp_components is not null)::text
  union all select 'info: rows with BMHP in invoice_items', null, (select count(*) from public.invoice_items where bmhp_components is not null)::text{CHECKS_TAIL}
-- QUERY B — migration history now records K02 (expect exactly one row).
select version, name from supabase_migrations.schema_migrations where version = '20261026100000';
"""
    rollback = f"""-- K02 ROLLBACK — WRITES TO THE DATABASE. Generated by build-and-verify.py; do not edit by hand.
-- Run ONLY after an explicit owner decision, and ONLY while no BMHP has been recorded (the first block
-- refuses otherwise; after real BMHP use the only safe path is roll-forward with a new migration).
-- Undo the app first if the K02 app code is already deployed (it then just refuses BMHP entry).
-- One transaction: any failure leaves the database exactly as before. Afterwards re-run preflight QUERY A:
-- it must show "0 failed" again (functions are back to their pre-K02 fingerprints).
begin;

do $guard$
begin
  if exists (select 1 from public.prescription_items where bmhp_components is not null)
     or exists (select 1 from public.invoice_items where bmhp_components is not null) then
    raise exception 'K02 rollback refused: BMHP data exists; roll forward instead';
  end if;
end $guard$;

-- Reverse the exact-anchor patches (same list as the migration, applied backwards: new text -> old text).
do $unpatch$
declare p record; definition text; signature regprocedure;
begin
 for p in select * from (select row_number() over () as n, v.* from (values
{VALUES}
 ) as v(sig, old_text, new_text)) as patches order by n desc loop
  signature := to_regprocedure(p.sig);
  if signature is null then raise exception 'K02 rollback missing RPC: %', p.sig; end if;
  definition := pg_get_functiondef(signature);
  if (length(definition) - length(replace(definition, p.new_text, ''))) / length(p.new_text) <> 1 then
   raise exception 'K02 rollback expected exactly one patched text in %: %', p.sig, left(p.new_text, 80);
  end if;
  execute replace(definition, p.new_text, p.old_text);
 end loop;
end $unpatch$;

drop trigger k02_invoice_item_bmhp on public.invoice_items;
drop trigger k02_prescription_bmhp on public.prescription_items;
drop function clinic_private.bmhp_edit_plan(uuid, jsonb, uuid, text);
drop function clinic_private.bmhp_issue(uuid, uuid, text, date);
drop function public.guard_invoice_item_bmhp();
drop function public.guard_prescription_bmhp();
drop function public.clinic_bmhp_supported();
alter table public.invoice_items drop column bmhp_components;
alter table public.prescription_items drop column bmhp_components;
-- schema clinic_private existed before K02 and is kept.

do $history$
begin
  if to_regclass('supabase_migrations.schema_migrations') is not null then
    delete from supabase_migrations.schema_migrations where version = '20261026100000';
  end if;
end $history$;

commit;
"""
    (HERE / '01-preflight-readonly.sql').write_text(preflight)
    (HERE / '03-readback-readonly.sql').write_text(readback)
    (HERE / '04-rollback-only-if-decided.sql').write_text(rollback)


def query(path, letter):
    text = path.read_text()
    start = text.index(f'-- QUERY {letter}')
    end = text.find('-- QUERY ', start + 5)
    return text[start:end if end > 0 else None]


def expect_all_ok(label, path):
    out = rows(query(path, 'A'))
    bad = [r for r in out if r[3] == 'f']
    LOG.append(f'{label}: {out[-1][2]} ({len(out) - 1} checks)')
    if bad:
        raise RuntimeError(f'{label} failed: {bad}')
    return out


def apply_k02():
    # Same as the SQL Editor path in OWNER-RUNBOOK.md: one transaction, file content verbatim, history row.
    psql('begin;\n' + source + "\ninsert into supabase_migrations.schema_migrations(version, name) values ('20261026100000', 'k02_procedure_bmhp');\ncommit;")


try:
    subprocess.run([BIN / 'initdb', '-D', DATA, '-U', 'postgres', '-E', 'UTF8', '--locale=en_US.UTF-8', '--auth=trust'], check=True, capture_output=True, env=ENV)
    SOCK.mkdir()
    with open(DATA / 'postgresql.conf', 'a') as conf:
        conf.write(f"\nlisten_addresses = ''\nunix_socket_directories = '{SOCK}'\nport = {PORT}\ntimezone = 'Etc/UTC'\n")
    if subprocess.run([BIN / 'pg_ctl', '-D', DATA, '-l', WORK / 'server.log', '-w', 'start'], capture_output=True, env=ENV).returncode:
        raise RuntimeError((WORK / 'server.log').read_text())
    LOG.append('server: ' + psql('select version()').stdout.split(',')[0])

    runner = (ROOT / 'scripts/test-procedure-bmhp-postgres.py').read_text()
    psql(re.search(r'sql\("""(.*?)"""\)', runner, re.S).group(1))
    psql('create schema supabase_migrations; create table supabase_migrations.schema_migrations(version text primary key, statements text[], name text);')
    migrations = sorted((ROOT / 'supabase/migrations').glob('*.sql'))
    assert migrations[-1] == MIG
    for m in migrations[:-1]:
        if m.name.startswith('0068'):
            psql("insert into coa_accounts(code,name,type,normal_balance) values('1101','Test cash','ASET','D'),('1102','Test bank','ASET','D') on conflict do nothing")
        version, _, name = m.stem.partition('_')
        psql(f"begin;\n{m.read_text()}\ninsert into supabase_migrations.schema_migrations(version, name) values ('{version}', '{name}') on conflict do nothing;\ncommit;")
    LOG.append(f'applied {len(migrations) - 1} migrations before K02 (target state the owner preflight expects)')

    pre = fingerprint(PATCHED)
    out = psql('begin;\n' + source + '\n' + ';\n'.join(
        f"select '{s}', md5(prosrc), prosecdef from pg_proc where oid = to_regprocedure('{s}')" for s in PATCHED + NEW) + ';\nrollback;').stdout
    post = {r[0]: r[1:] for r in (line.split('|') for line in out.splitlines()) if len(r) == 3}
    assert set(post) == set(PATCHED + NEW), post
    render(pre, post)
    LOG.append('generated 01-preflight-readonly.sql, 03-readback-readonly.sql, 04-rollback-only-if-decided.sql')

    pre_path, back_path, rb_path = HERE / '01-preflight-readonly.sql', HERE / '03-readback-readonly.sql', HERE / '04-rollback-only-if-decided.sql'
    expect_all_ok('preflight A before apply', pre_path)
    LOG.append('preflight B newest: ' + ' '.join(rows(query(pre_path, 'B'))[0]))
    LOG.append(f"preflight C rows: {len(psql(query(pre_path, 'C')).stdout.split('CREATE OR REPLACE FUNCTION')) - 1}")

    apply_k02()
    expect_all_ok('readback A after apply', back_path)
    LOG.append('readback B: ' + ' '.join(rows(query(back_path, 'B'))[0]))
    failed = [r[0] for r in rows(query(pre_path, 'A')) if r[3] == 'f']
    LOG.append(f'preflight A re-run after apply correctly reports {len(failed)} failed checks (already applied)')

    # Rollback refuses once BMHP data exists (row inserted with triggers off, then discarded).
    refused = psql("begin;\nset local session_replication_role = replica;\n"
                   "insert into public.prescription_items(medical_record_id, nama_obat, qty, harga, jenis, bmhp_components)"
                   " values (gen_random_uuid(), 'rehearsal', 1, 0, 'jasa', '[]');\n" + rb_path.read_text(), check=False)
    assert refused.returncode and 'K02 rollback refused: BMHP data exists' in refused.stderr, refused.stderr
    psql('rollback;')
    expect_all_ok('readback A after refused rollback (nothing changed)', back_path)

    psql(rb_path.read_text())
    expect_all_ok('preflight A after rollback (back to pre-K02 fingerprints)', pre_path)
    LOG.append('history after rollback newest: ' + ' '.join(rows(query(pre_path, 'B'))[0]))

    apply_k02()
    expect_all_ok('readback A after re-apply', back_path)
    psql((ROOT / 'supabase/tests/clinic_procedure_bmhp.sql').read_text())
    LOG.append('clinic_procedure_bmhp.sql after rollback + re-apply: passed (FIFO)')
    LOG.append('REHEARSAL PASSED')
finally:
    if (DATA / 'postmaster.pid').exists():
        subprocess.run([BIN / 'pg_ctl', '-D', DATA, '-m', 'immediate', 'stop'], capture_output=True)
    shutil.rmtree(WORK, ignore_errors=True)
    LOG.append('cleanup: temp cluster removed' if not WORK.exists() else f'cleanup FAILED: {WORK}')
    print('\n'.join(LOG))
