#!/usr/bin/env python3
"""Regenerate apply.sql from the three PR #310 migrations, then rehearse the owner package on a throwaway
native PostgreSQL cluster (no Docker, no database URL, fictional data only). Production order is mimicked:
every other repository migration first (including later ones already on main), then the package.

  baseline -> preflight -> apply -> readback -> apply again (refused, nothing changes)
  -> rollback (functions byte-identical to baseline, triggers/sources/history back) -> preflight
  -> apply -> readback -> K08/A01/Q01 SQL suites.

Usage: LC_ALL=C.UTF-8 python3 docs/evidence/2026-10-29-pr310-k08-a01-q01/owner-apply/build-and-rehearse.py [pg bin dir]
"""
from pathlib import Path
import hashlib
import sys

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
from native_postgres import NativePostgres  # noqa: E402

MIGRATIONS = ["20261030110000_k08_inpatient_redischarge_days.sql",
              "20261030111000_a01_activity_audit_new_sources.sql",
              "20261030112000_q01_staff_effects_recovery.sql"]
TABLES = ["campaign_codes", "payslip_templates", "payslip_template_components", "employee_payslip_templates",
          "employee_base_salaries", "service_commission_policies", "branch_grooming_rules", "opening_invoice_batches",
          "opening_invoice_lines", "recurring_journal_sources", "clinic_refund_items", "clinic_record_addenda",
          "inpatient_rx_evidence", "inpatient_rx_evidence_settings", "purchase_invoice_receipts",
          "quest_new_customer_claims", "clinic_refund_requests", "clinic_refunds", "clinic_history_reads"]
BIN = sys.argv[1] if len(sys.argv) > 1 else "/usr/lib/postgresql/16/bin"

sources = {m: (ROOT / "supabase/migrations" / m).read_text() for m in MIGRATIONS}
table_list = ",".join(f"'{t}'" for t in TABLES)
apply_sql = (
    "-- PR #310 (K08 + A01 + Q01) APPLY — WRITES. Generated by build-and-rehearse.py; do not edit by hand.\n"
    "-- One transaction: saves the two functions it patches (for rollback.sql), then the three migrations verbatim\n"
    + "".join(f"--   supabase/migrations/{m} (sha256 {hashlib.sha256(sources[m].encode()).hexdigest()})\n" for m in MIGRATIONS)
    + "-- plus their history rows. Any error, a lock wait over 5 s, or a role other than postgres rolls everything back.\n"
    "begin;\nset local lock_timeout = '5s';\nset local statement_timeout = '120s';\n"
    "do $guard$ begin\n"
    "  if current_user <> 'postgres' then raise exception 'PR310: must run as postgres'; end if;\n"
    "  if exists(select 1 from supabase_migrations.schema_migrations where version in ('20261030110000','20261030111000','20261030112000'))\n"
    "     or to_regclass('vetos_release.pr310_backup') is not null then\n"
    "    raise exception 'PR310_ALREADY_APPLIED: run readback.sql';\n  end if;\nend $guard$;\n"
    "create schema if not exists vetos_release;\n"
    "revoke all on schema vetos_release from public, anon, authenticated, service_role;\n"
    "create table vetos_release.pr310_backup(kind text not null, name text not null, payload text, primary key (kind, name));\n"
    "revoke all on table vetos_release.pr310_backup from public, anon, authenticated, service_role;\n"
    "insert into vetos_release.pr310_backup(kind, name, payload) values\n"
    " ('function', 'public.clinic_change_inpatient_condition(uuid,text,text)', pg_get_functiondef('public.clinic_change_inpatient_condition(uuid,text,text)'::regprocedure)),\n"
    " ('function', 'public.apply_sale_staff_effects(uuid)', pg_get_functiondef('public.apply_sale_staff_effects(uuid)'::regprocedure));\n"
    "insert into vetos_release.pr310_backup(kind, name, payload)\n"
    " select 'trigger', c.relname || '.' || g.tgname, pg_get_triggerdef(g.oid) from pg_trigger g join pg_class c on c.oid = g.tgrelid\n"
    f"  where c.relnamespace = 'public'::regnamespace and not g.tgisinternal and c.relname in ({table_list})\n"
    "    and g.tgname in ('a01_activity_change', 'a01_activity_delete');\n"
    "insert into vetos_release.pr310_backup(kind, name)\n"
    f" select 'source', entity from public.activity_log_sources where entity in ({table_list});\n\n"
    + "\n".join(sources[m] for m in MIGRATIONS)
    + "\ninsert into supabase_migrations.schema_migrations(version, name) values\n"
    + ",\n".join(f" ('{m[:14]}', '{m[15:-4]}')" for m in MIGRATIONS) + ";\ncommit;\n")
(HERE / "apply.sql").write_text(apply_sql)

SHIM = """create extension if not exists pgcrypto;
create role anon; create role authenticated; create role service_role bypassrls;
create schema auth; create schema storage; create schema supabase_migrations;
create table supabase_migrations.schema_migrations(version text primary key, statements text[], name text);
create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_user_meta_data jsonb default '{}');
create function auth.uid() returns uuid language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid$$;
create function auth.role() returns text language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claim.role',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'role')$$;
create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
create table storage.buckets(id text primary key,name text,public boolean);
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,owner uuid);
create publication supabase_realtime;
grant usage on schema public,auth,storage to authenticated,anon,service_role;
grant execute on all functions in schema auth to authenticated,anon,service_role;
alter default privileges in schema public grant all on tables to authenticated,service_role;
alter default privileges in schema public grant all on sequences to authenticated,service_role;"""

STATE = f"""select md5(pg_get_functiondef('public.clinic_change_inpatient_condition(uuid,text,text)'::regprocedure))
 || md5(pg_get_functiondef('public.apply_sale_staff_effects(uuid)'::regprocedure))
 || coalesce((select string_agg(pg_get_triggerdef(g.oid), ',' order by c.relname, g.tgname) from pg_trigger g join pg_class c on c.oid = g.tgrelid
     where not g.tgisinternal and c.relname in ({table_list}) and g.tgname like 'a01_%'), '')
 || coalesce((select string_agg(entity, ',' order by entity) from public.activity_log_sources where entity in ({table_list})), '')
 || (select count(*) from supabase_migrations.schema_migrations)::text
 || (to_regprocedure('public.apply_pending_sale_staff_effects()') is null)::text
 || (to_regclass('public.sales_staff_effects_pending_idx') is null)::text
 || (to_regnamespace('vetos_release') is null)::text;"""


def checked(db, name, path):
    out = db.sql(path.read_text())
    rows = [r.split("|") for r in out.splitlines() if r.strip()]
    summary = [r for r in rows if r[0] == "SUMMARY"]
    bad = [r for r in rows if r[0] != "SUMMARY" and r[-1] == "f"]
    if bad or not summary or summary[0][2] != "0 failed":
        raise RuntimeError(f"{name} not ok: {bad or summary}")
    print(f"{name}: {len(rows) - 1} checks, 0 failed", flush=True)


with NativePostgres(BIN) as db:
    db.sql(SHIM)
    rest = [m for m in sorted((ROOT / "supabase/migrations").glob("*.sql")) if m.name not in MIGRATIONS]
    for m in rest:
        if m.name.startswith("0068"):
            db.sql("insert into coa_accounts(code,name,type,normal_balance) values('1101','Test cash','ASET','D'),('1102','Test bank','ASET','D') on conflict do nothing;")
        try:
            db.sql("begin;\n" + m.read_text() + "\ncommit;")
        except RuntimeError as error:
            raise RuntimeError(m.name + ": " + str(error)) from error
        db.sql(f"insert into supabase_migrations.schema_migrations(version, name) values ('{m.name.split('_')[0]}', '{m.stem}') on conflict do nothing;")
    print(f"baseline: {len(rest)} other migrations applied ({db.sql('show server_version')})", flush=True)
    base = db.sql(STATE)
    checked(db, "preflight", HERE / "preflight.sql")
    db.sql(apply_sql)
    checked(db, "readback", HERE / "readback.sql")
    after = db.sql(STATE)
    try:
        db.sql(apply_sql)
        raise SystemExit("second apply must be refused")
    except RuntimeError as error:
        assert "PR310_ALREADY_APPLIED" in str(error), error
    assert db.sql(STATE) == after, "refused re-apply changed state"
    print("apply again: refused with PR310_ALREADY_APPLIED, nothing changed", flush=True)
    db.sql((HERE / "rollback.sql").read_text())
    assert db.sql(STATE) == base, f"rollback state differs:\n{base}\n{db.sql(STATE)}"
    print("rollback: functions byte-identical, triggers/sources/history/index/schema as before apply", flush=True)
    checked(db, "preflight after rollback", HERE / "preflight.sql")
    db.sql(apply_sql)
    checked(db, "readback after re-apply", HERE / "readback.sql")
    for suite in ["clinic_inpatient_discharge.sql", "inpatient_continuation_pet_hotel.sql", "clinic_billing_lifecycle.sql",
                  "activity_audit_coverage.sql", "activity_audit_framework.sql", "q01_new_customer_quest.sql", "c05_q01_followup.sql"]:
        db.sql((ROOT / "supabase/tests" / suite).read_text())
        print("PASS", suite, flush=True)
    print("apply.sql sha256", hashlib.sha256(apply_sql.encode()).hexdigest(), flush=True)
