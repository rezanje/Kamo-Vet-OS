#!/usr/bin/env python3
"""M05 owner package: generate 02-apply.sql from the migration and rehearse the whole package.

02-apply.sql = the migration verbatim + history row in one transaction (generated; never edit by hand).
01/03/04 are hand-written and only rehearsed here.

Rehearsal on a throwaway native cluster (scripts/native_postgres.py: unix socket only, no Docker, no DB URL,
deleted afterwards), fictional fixtures only:
  all repository migrations + simulated migration history → 04 rollback on an empty install (proves rollback) →
  01 preflight 0 failed → 02 apply → 03 readback 0 failed → 02 again refused, nothing changed →
  M05 SQL suite (rolled back) → one fictional batch committed → 04 rollback refused, data intact → 03 still 0 failed
  except the "no batch posted yet" row.

Usage: python3 docs/evidence/2026-10-27-m05-opening-invoices/owner-apply/build-and-verify.py BIN_DIR [--write]
  Without --write, a 02-apply.sql that differs from the generated text fails the run.
"""
import hashlib
import importlib.util
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
from native_postgres import NativePostgres  # noqa: E402

VERSION, NAME = "20261027180000", "opening_ap_ar_invoices"
MIGRATION = ROOT / "supabase/migrations" / f"{VERSION}_{NAME}.sql"
SUITE = ROOT / "supabase/tests/opening_ap_ar_invoices.sql"


def apply_sql():
    text = MIGRATION.read_text()
    digest = hashlib.sha256(text.encode()).hexdigest()
    return (f"-- M05 APPLY — WRITES. Generated by build-and-verify.py; do not edit by hand.\n"
            f"-- One transaction: migration {MIGRATION.name} verbatim (sha256 {digest}) plus its history row.\n"
            "-- Any error, a lock wait over 5 s, or running as a role other than postgres rolls everything back.\n"
            "begin;\nset local lock_timeout = '5s';\nset local statement_timeout = '60s';\n"
            "do $$ begin\n  if current_user <> 'postgres' then\n"
            "    raise exception 'M05 apply must run as postgres (current role: %); nothing was applied', current_user;\n  end if;\n"
            f"  if exists(select 1 from supabase_migrations.schema_migrations where version = '{VERSION}') then\n"
            "    raise exception 'M05_ALREADY_APPLIED: history row exists; nothing was applied';\n  end if;\nend $$;\n\n"
            + text.rstrip("\n") + "\n\n"
            f"insert into supabase_migrations.schema_migrations(version, name) values ('{VERSION}', '{NAME}');\ncommit;\n")


def summary_ok(output, label):
    last = output.strip().splitlines()[-1]
    assert last.startswith("SUMMARY|0 failed|0 failed|t"), f"{label} did not pass:\n{output}"


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    generated = apply_sql()
    target = HERE / "02-apply.sql"
    if "--write" in sys.argv:
        target.write_text(generated)
    elif not target.exists() or target.read_text() != generated:
        sys.exit("02-apply.sql differs from the generated text; rerun with --write and review the diff")
    if sys.platform == "darwin":
        os.environ.setdefault("LC_ALL", "en_US.UTF-8")
    spec = importlib.util.spec_from_file_location("fixture", ROOT / "scripts/test-accurate-inventory-accounting-postgres.py")
    fixture = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fixture)
    log = []
    say = lambda line: (print(line, flush=True), log.append(line))
    files = {name: (HERE / name).read_text() for name in ["01-preflight-readonly.sql", "02-apply.sql", "03-readback-readonly.sql", "04-rollback-only-if-unused.sql"]}
    for name, text in files.items():
        say(f"sha256 {hashlib.sha256(text.encode()).hexdigest()}  {name}")
    say(f"sha256 {hashlib.sha256(MIGRATION.read_bytes()).hexdigest()}  {MIGRATION.relative_to(ROOT)}")
    with NativePostgres(sys.argv[1]) as db:
        fixture.DisposablePostgres.bootstrap(db)
        server = db.sql("show server_version")
        say(f"Bootstrapped {len(list((ROOT / 'supabase/migrations').glob('*.sql')))} repository migrations on PostgreSQL {server}")
        versions = sorted(p.name.split("_", 1) for p in (ROOT / "supabase/migrations").glob("*.sql"))
        db.sql("create schema supabase_migrations; create table supabase_migrations.schema_migrations(version text primary key, statements text[], name text);\n"
               + "".join(f"insert into supabase_migrations.schema_migrations(version,name) values('{v}','{n[:-4]}') on conflict do nothing;\n" for v, n in versions))
        db.sql("insert into coa_accounts(code,name,type,normal_balance) values('2101','Fiction AP','LIABILITAS','K'),('1201','Fiction AR','ASET','D'),('3101','Fiction equity','EKUITAS','K') on conflict do nothing;")
        say("Simulated migration history (all versions recorded) and fictional COA 2101/1201/3101")
        db.sql(files["04-rollback-only-if-unused.sql"])
        assert db.sql("select to_regclass('public.opening_invoice_batches') is null and not exists(select 1 from information_schema.columns where column_name='opening_batch_id')") == "t"
        say("PASS 04 rollback on an empty install removed every M05 object and the history row")
        summary_ok(db.sql(files["01-preflight-readonly.sql"]), "preflight")
        say("PASS 01 preflight: 0 failed")
        db.sql(files["02-apply.sql"])
        say("PASS 02 apply")
        summary_ok(db.sql(files["03-readback-readonly.sql"]), "readback")
        say("PASS 03 readback: 0 failed")
        try:
            db.sql(files["02-apply.sql"])
            raise AssertionError("second apply was accepted")
        except RuntimeError as error:
            assert "M05_ALREADY_APPLIED" in str(error), error
        summary_ok(db.sql(files["03-readback-readonly.sql"]), "readback after refused re-apply")
        say("PASS second 02 apply refused (M05_ALREADY_APPLIED); readback unchanged")
        db.sql(SUITE.read_text())
        say("PASS M05 SQL suite (rolled back)")
        db.sql(SUITE.read_text().rsplit("rollback;", 1)[0] + "commit;\n")
        posted = db.sql("select count(*) from opening_invoice_batches; select count(*) from purchase_invoices where opening_batch_id is not null;").splitlines()
        assert posted == ["1", "3"], posted
        say("Committed one fictional batch (3 payables, 1 receivable)")
        try:
            db.sql(files["04-rollback-only-if-unused.sql"])
            raise AssertionError("rollback accepted with posted data")
        except RuntimeError as error:
            assert "M05_ROLLBACK_REFUSED" in str(error), error
        assert db.sql("select count(*) from opening_invoice_batches; select count(*) from purchase_invoices where opening_batch_id is not null;").splitlines() == ["1", "3"]
        failed = [line for line in db.sql(files["03-readback-readonly.sql"]).splitlines() if line.endswith("|f")]
        assert failed == ["data: no batch posted yet|0|1|f", "SUMMARY|0 failed|1 failed|f"], failed
        say("PASS 04 rollback refused once a batch exists (M05_ROLLBACK_REFUSED); invoices and batch intact")
    (HERE / f"rehearsal-pg{server.split()[0]}.log").write_text("\n".join(log) + "\n")


if __name__ == "__main__":
    main()
