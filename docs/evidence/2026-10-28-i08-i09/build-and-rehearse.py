#!/usr/bin/env python3
"""I08/I09 owner package: regenerate apply.sql from the three migrations, then rehearse
preflight -> apply -> readback -> apply again (idempotent) -> rollback (must restore the exact
pre-apply function bodies) -> preflight -> apply -> readback -> production SQL suite,
on a disposable PostgreSQL (the repo's Docker runner; use the native wrapper without Docker).
Fictional data only; never accepts a database URL."""
from pathlib import Path
import hashlib
import importlib.util
import sys

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
MIGRATIONS = ['20261028200000_i08_production_average_costing.sql',
              '20261028201000_i08_production_job_completion_links.sql',
              '20261028202000_i09_compound_trace.sql']

apply_sql = ('-- I08/I09 APPLY — WRITES. Generated by build-and-rehearse.py from the three migrations; do not edit.\n'
             '-- One transaction; idempotent (safe to run twice). Run preflight.sql first, readback.sql after.\n'
             'begin;\n' + ''.join(f'\n-- ===== {name} =====\n' + (ROOT / 'supabase/migrations' / name).read_text() for name in MIGRATIONS)
             + '\ncommit;\n')
(HERE / 'apply.sql').write_text(apply_sql)
print('apply.sql sha256', hashlib.sha256(apply_sql.encode()).hexdigest())

spec = importlib.util.spec_from_file_location('isolated', ROOT / 'scripts/test-accurate-inventory-accounting-postgres.py')
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

FINGERPRINT = """select md5(pg_get_functiondef('public.post_production_atomic(text,text,jsonb)'::regprocedure))||
 md5(pg_get_functiondef('public.post_production_adhoc_atomic(text,text,jsonb)'::regprocedure))||
 md5(pg_get_functiondef('public.read_production_atomic_sources(uuid[])'::regprocedure))||
 (to_regprocedure('public.read_compound_trace(uuid)') is null)::text;"""


def all_ok(db, file):
    out = db.sql((HERE / file).read_text()).splitlines()
    checks = [line for line in out if line.endswith('|t') or line.endswith('|f')]
    if not checks or any(line.endswith('|f') for line in checks[:6]):
        raise AssertionError(f'{file} failed: {out}')
    print(f'PASS {file} ({len(checks)} checks)', flush=True)


class Pre(m.DisposablePostgres):
    def bootstrap(self):
        original = sorted((ROOT / 'supabase/migrations').glob('*.sql'))
        keep = [p for p in original if p.name not in MIGRATIONS]
        glob = Path.glob
        Path.glob = lambda self, pattern: keep if self == ROOT / 'supabase/migrations' else glob(self, pattern)
        try:
            super().bootstrap()
        finally:
            Path.glob = glob


with Pre() as db:
    db.bootstrap()
    before = db.sql(FINGERPRINT)
    all_ok(db, 'preflight.sql')
    db.sql(apply_sql)
    all_ok(db, 'readback.sql')
    db.sql(apply_sql)
    all_ok(db, 'readback.sql')
    print('PASS apply is idempotent', flush=True)
    db.sql((HERE / 'rollback.sql').read_text())
    if db.sql(FINGERPRINT) != before:
        raise AssertionError('rollback did not restore the exact pre-apply function bodies')
    print('PASS rollback restores exact pre-apply function bodies', flush=True)
    all_ok(db, 'preflight.sql')
    db.sql(apply_sql)
    all_ok(db, 'readback.sql')
    for name in ['production_atomic.sql', 'production_adhoc.sql', 'production_average.sql', 'production_trace_i08_i09.sql']:
        db.sql((ROOT / 'supabase/tests' / name).read_text())
        print('PASS ' + name, flush=True)
