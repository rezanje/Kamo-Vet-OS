#!/usr/bin/env python3
"""Regenerate apply.sql from the migration, then rehearse the owner package on a throwaway native
PostgreSQL 16 cluster (no Docker, no database URL, fictional data only):

  all earlier repository migrations -> preflight -> apply -> readback -> apply again (idempotent)
  -> group-payment data -> rollback without flag (functions byte-identical, data archived) -> preflight
  -> apply -> rollback with owner flag (column dropped) -> preflight -> apply -> readback -> SQL suites.

Usage (Linux, as root; the server runs as the `postgres` OS user):
  python3 docs/evidence/2026-10-29-c05-coverage/owner-apply/build-and-rehearse.py [/usr/lib/postgresql/16/bin]
"""
from pathlib import Path
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
MIGRATION = '20261029154000_c05_campaign_rombongan_backoffice.sql'
BIN = Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/lib/postgresql/16/bin')

header = ('-- C05 follow-up (group payment + back-office) apply. WRITES. Generated by build-and-rehearse.py from (keep in sync):\n'
          f'--   supabase/migrations/{MIGRATION}\n'
          '-- Requires the base C05 step (20261028181000_c05_campaign_codes.sql) already applied.\n'
          '-- Idempotent: re-running is harmless. Run preflight.sql first and readback.sql after.\nbegin;\n')
(HERE / 'apply.sql').write_text(header + (ROOT / 'supabase/migrations' / MIGRATION).read_text() + '\ncommit;\n')

for key in [k for k in os.environ if k.startswith('PG')]:
    del os.environ[key]
os.environ.update(PSQLRC='/dev/null', TZ='Etc/UTC', LC_ALL='C.UTF-8')
WORK = Path(tempfile.mkdtemp(prefix='vetos-c05cov-own-', dir='/tmp'))
DATA, SOCK, PORT = WORK / 'data', WORK / 'sock', '54338'
SOCK.mkdir()
AS_SERVER = ['runuser', '-u', 'postgres', '--'] if os.geteuid() == 0 else []
if AS_SERVER:
    for path in (WORK, SOCK):
        shutil.chown(path, 'postgres')


def server(*args):
    subprocess.run([*AS_SERVER, *map(str, args)], cwd=WORK, check=True, capture_output=True)


def psql(source, tuples=True):
    args = [BIN / 'psql', '-h', SOCK, '-p', PORT, '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-q']
    if tuples:
        args.append('-At')
    r = subprocess.run(args, input=source, text=True, capture_output=True)
    if r.returncode:
        raise RuntimeError(r.stderr)
    return r.stdout


def all_ok(name, out):
    rows = [line.split('|') for line in out.strip().splitlines()]
    bad = [r for r in rows if r[-1] != 't']
    if bad:
        raise RuntimeError(f'{name} not ok: {bad}')
    print(f'{name}: {len(rows)} rows ok')


FN = ("select md5(pg_get_functiondef('public.guard_campaign_code_use()'::regprocedure)) || ' '"
      " || md5(pg_get_functiondef('public.campaign_code_used(text)'::regprocedure)) || ' '"
      " || md5(pg_get_functiondef('public.clinic_post_invoice(uuid,text,jsonb,jsonb)'::regprocedure)) || ' '"
      " || (select pg_get_triggerdef(oid) from pg_trigger where tgname = 'c05_invoice_campaign_code')")
SEED = """
insert into public.branches (id, code, name, type) values ('0c100000-0000-4000-8000-000000000001', 'RBK', 'Rehearsal klinik', 'KLINIK') on conflict do nothing;
insert into public.customers (id, name, phone) values ('0c400000-0000-4000-8000-000000000001', 'Rehearsal owner', '081200000901') on conflict do nothing;
insert into public.pets (id, customer_id, name) values ('0c500000-0000-4000-8000-00000000000{n}', '0c400000-0000-4000-8000-000000000001', 'RB{n}');
insert into public.visits (id, branch_id, customer_id, pet_id) values ('0c600000-0000-4000-8000-00000000000{n}',
  '0c100000-0000-4000-8000-000000000001', '0c400000-0000-4000-8000-000000000001', '0c500000-0000-4000-8000-00000000000{n}');
insert into public.vouchers (id, code, tipe, nilai) values ('0c300000-0000-4000-8000-00000000000{n}', 'RBV{n}', 'nominal', 1000);
insert into public.campaign_codes (code, voucher_id, max_uses) values ('RBGRUP{n}', '0c300000-0000-4000-8000-00000000000{n}', 1);
insert into public.invoices (visit_id, invoice_no, subtotal, discount, total, paid_status, voucher_code, campaign_code, campaign_group)
  values ('0c600000-0000-4000-8000-00000000000{n}', 'RB-INV-{n}', 5000, 1000, 4000, 'Lunas', 'RBV{n}', 'RBGRUP{n}',
          '0c400000-0000-4000-8000-000000000001:' || to_char(now() at time zone 'Asia/Jakarta', 'YYYY-MM-DD'));
"""
COLUMNS = "select string_agg(column_name, ',' order by column_name) from information_schema.columns where table_schema = 'public' and table_name = 'invoices' and column_name like 'campaign_group%'"
try:
    server(BIN / 'initdb', '-D', DATA, '-U', 'postgres', '-E', 'UTF8', '--locale=C.UTF-8', '--auth=trust')
    with open(DATA / 'postgresql.conf', 'a') as conf:
        conf.write(f"\nlisten_addresses = ''\nunix_socket_directories = '{SOCK}'\nport = {PORT}\ntimezone = 'Etc/UTC'\n")
    server(BIN / 'pg_ctl', '-D', DATA, '-l', WORK / 'server.log', '-w', 'start')
    print('server:', subprocess.run([BIN / 'postgres', '--version'], capture_output=True, text=True).stdout.strip())
    psql("""create role anon; create role authenticated; create role service_role bypassrls;
create schema auth; create schema storage;
create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_user_meta_data jsonb default '{}');
create function auth.uid() returns uuid language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid$$;
create function auth.role() returns text language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claim.role',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'role')$$;
create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),'')::jsonb,'{}'::jsonb)$$;
create table storage.buckets(id text primary key,name text,public boolean);
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,owner uuid);
create publication supabase_realtime;
grant usage on schema public,auth,storage to authenticated,anon,service_role;
grant execute on all functions in schema auth to authenticated,anon,service_role;
alter default privileges in schema public grant all on tables to authenticated,service_role;
alter default privileges in schema public grant all on sequences to authenticated,service_role;""")
    earlier = [m for m in sorted((ROOT / 'supabase/migrations').glob('*.sql')) if m.name != MIGRATION]
    for m in earlier:
        if m.name.startswith('0068'):
            psql("insert into coa_accounts(code,name,type,normal_balance) values('1101','Test cash','ASET','D'),('1102','Test bank','ASET','D') on conflict do nothing")
        psql('begin;\n' + m.read_text() + '\ncommit;')
    print(f'baseline: {len(earlier)} earlier migrations applied (production state before this step)')
    base = psql(FN).strip()
    all_ok('preflight (before)', psql((HERE / 'preflight.sql').read_text()))
    psql((HERE / 'apply.sql').read_text())
    all_ok('readback', psql((HERE / 'readback.sql').read_text()))
    applied = psql(FN).strip()
    psql((HERE / 'apply.sql').read_text())
    if psql(FN).strip() != applied:
        raise RuntimeError('re-apply changed the patched functions')
    all_ok('readback after re-apply (idempotent, functions byte-identical)', psql((HERE / 'readback.sql').read_text()))

    # Rollback without the owner flag: functions/trigger back to baseline byte-for-byte; group keys archived.
    psql(SEED.format(n=1))
    psql((HERE / 'rollback.sql').read_text())
    if psql(FN).strip() != base:
        raise RuntimeError('rollback did not restore functions/trigger byte-for-byte')
    if psql(COLUMNS).strip() != 'campaign_group_archived_c05cov':
        raise RuntimeError('rollback without flag must archive the data-bearing column: ' + psql(COLUMNS))
    print('rollback (default): functions + trigger identical to baseline; group keys kept in campaign_group_archived_c05cov')
    all_ok('preflight (after rollback)', psql((HERE / 'preflight.sql').read_text()))
    psql((HERE / 'apply.sql').read_text())
    if psql(FN).strip() != applied:
        raise RuntimeError('apply after rollback differs from first apply')
    all_ok('readback (re-apply over archive)', psql((HERE / 'readback.sql').read_text()))

    # Rollback with the explicit owner flag: column dropped.
    psql(SEED.format(n=2))
    psql("select set_config('vetos.rollback_drop_data', 'yes', false);\n" + (HERE / 'rollback.sql').read_text())
    if psql(FN).strip() != base or psql(COLUMNS).strip() != 'campaign_group_archived_c05cov':
        raise RuntimeError('rollback with flag must restore functions and drop the live column')
    print('rollback (owner flag): functions + trigger identical to baseline; live group-key column dropped')
    all_ok('preflight (after flagged rollback)', psql((HERE / 'preflight.sql').read_text()))
    psql((HERE / 'apply.sql').read_text())
    all_ok('readback (final apply)', psql((HERE / 'readback.sql').read_text()))
    for suite in ['c05_campaign_rombongan_backoffice.sql', 'c05_campaign_codes.sql']:
        print(suite + ': ' + psql((ROOT / 'supabase/tests' / suite).read_text()).strip().splitlines()[-1])
    print('apply.sql sha256', hashlib.sha256((HERE / 'apply.sql').read_bytes()).hexdigest())
finally:
    if (DATA / 'postmaster.pid').exists():
        subprocess.run([*AS_SERVER, str(BIN / 'pg_ctl'), '-D', str(DATA), '-m', 'immediate', 'stop'], cwd=WORK, capture_output=True)
    shutil.rmtree(WORK, ignore_errors=True)
    print('cleanup: temp cluster removed' if not WORK.exists() else f'cleanup FAILED: {WORK}')
