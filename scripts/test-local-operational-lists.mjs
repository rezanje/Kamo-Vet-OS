import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const {chromium} = require('playwright');
(async () => {
  // Fictional local fixture only; login and reads never target a remote host.
  const app = new URL(process.env.VETOS_LIST_TEST_URL || 'http://127.0.0.1:3110');
  if (!['127.0.0.1','localhost','[::1]'].includes(app.hostname)) throw new Error('Local loopback app required');
  const manifest = JSON.parse(fs.readFileSync('/workspace/hris-local-runtime/fixture-manifest.json','utf8'));
  const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  const context = await browser.newContext({baseURL:app.origin,timezoneId:'Asia/Jakarta'});
  await context.route('**/*', route => new URL(route.request().url()).origin === app.origin ? route.continue() : route.abort());
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.goto('/login');
    await page.locator('[name=email]').fill('owner@hris-fiction.local');
    await page.locator('[name=password]').fill('FictionLocalOnly123!');
    await Promise.all([page.waitForURL('**/mulai',{timeout:60000}),page.getByRole('button',{name:'Masuk',exact:true}).click()]);
    await page.goto('/crm/pelanggan');
    const customerRows=page.locator('.ct table tbody').first().locator('tr');
    await customerRows.first().waitFor();
    assert.equal(await customerRows.count(),50);
    const nav=page.getByRole('navigation',{name:'Halaman pelanggan'});
    assert.match(await nav.innerText(),/1200 pelanggan/);
    await nav.getByRole('button',{name:'Berikutnya'}).click();
    assert.match(await nav.innerText(),/Halaman 2\/24/);
    await page.getByPlaceholder('Cari nama / no. HP...').fill('Fiction QA customer 1200');
    await page.waitForTimeout(150);
    assert.equal(await customerRows.count(),1);
    assert.match(await customerRows.innerText(),/customer 1200/);
    assert.match(await nav.innerText(),/Halaman 1\/1/);
    await page.getByPlaceholder('Cari nama / no. HP...').fill('');
    assert.equal(await customerRows.count(),50);
    assert.match(await nav.innerText(),/Halaman 1\/24/);
    await page.goto('/klinik/rekam-medis?hal=7');
    const rows=page.locator('.ct table tbody').first().locator('tr');
    await rows.first().waitFor();
    assert.equal(await rows.count(),50);
    const actualMedicalTotal=Number((await page.getByRole('navigation',{name:'Halaman daftar'}).innerText()).match(/dari (\d+)/)[1]);
    assert.ok(actualMedicalTotal>=350);
    const oldName=(await rows.first().locator('td').nth(1).innerText()).split('\n')[0];
    await page.goto('/klinik/rekam-medis?q='+encodeURIComponent(oldName));
    await page.locator('.ct table tbody').first().waitFor();
    assert.ok((await page.locator('.ct table tbody').first().innerText()).includes(oldName));
    await page.goto('/pos/stok?wh='+manifest.benchmarkWarehouse+'&hal=24');
    await page.locator('.ct table tbody').first().waitFor();
    assert.equal(await page.locator('.ct table tbody').first().locator('tr').count(),50);
    assert.match(await page.getByRole('navigation',{name:'Halaman daftar'}).innerText(),/dari 1200/);
    await page.goto('/pos/stok?wh=all&hal=24');
    await page.locator('.ct table tbody').first().waitFor();
    assert.equal(await page.locator('.ct table tbody').first().locator('tr').count(),50);
    assert.match(await page.locator('.ct').innerText(),/1200 barang/);
    const prev=page.getByRole('navigation',{name:'Halaman daftar'}).getByRole('link',{name:'Sebelumnya'});
    assert.match(await prev.getAttribute('href'),/wh=all&hal=23/);
    assert.equal(errors.length,0,errors.join('\n'));
    console.log(JSON.stringify({completed:true,customerRows:50,totalCustomers:1200,searchBeyondCap:true,searchResets:true,medicalRows:50,totalMedical:actualMedicalTotal,oldMedicalSearch:true,warehouseRows:50,matrixRows:50,totalStock:1200,browserErrors:errors.length}));
  } finally { await context.close();await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1});
